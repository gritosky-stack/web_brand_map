import Foundation

/// Сколько займёт маршрут у одного среднего человека.
///
/// Модель наизмитовская — километры плюс набор высоты, — но коэффициенты не
/// книжные, а **подобранные по пройденным трекам**: 14 записей из `www/*.gpx`
/// с настоящими временными метками, из них 10 с полным профилем высот.
///
/// Классические 5 км/ч + 1 минута на 10 м набора ошибались на этих треках в
/// среднем на 35 % (два часа на дневном маршруте). Подобранные — на 14 %.
///
/// Два важных уточнения, без которых числа не переносятся:
///
/// * это **общее время от старта до финиша**, с привалами и фотостопами, а не
///   чистое ходовое. Так его и меряют по треку, и так его и планируют;
/// * набор берётся тот, что считает `GPXParser` — после фильтра выбросов и
///   сглаживания окном 15 точек. По сырым точкам набор выходит в полтора раза
///   больше, и коэффициент к нему уже не подходит.
///
/// Точность честная: типичная ошибка около 14 %, то есть ±45 минут на дневном
/// маршруте. Разброс задаёт не формула, а привалы: на одном и том же маршруте
/// один и тот же человек тратит от пяти до семи часов.
enum HikingTime {

    /// Ровная скорость. Взята круглой: свободная подгонка давала 4.85 км/ч при
    /// ровно той же ошибке, а круглое число не создаёт ложного впечатления,
    /// будто коэффициент известен до сотых.
    static let flatSpeedKmh = 4.5

    /// Метров набора на минуту. У Наизмита здесь 10 м, но у него и время
    /// чистое ходовое, и набор по сырому профилю.
    static let metersPerMinuteOfClimb = 4.3

    /// Оценка для одного среднего человека, в минутах.
    static func minutes(distanceKm: Double, ascentM: Double) -> Double {
        guard distanceKm > 0 || ascentM > 0 else { return 0 }
        return distanceKm / flatSpeedKmh * 60 + ascentM / metersPerMinuteOfClimb
    }

    static func minutes(_ stats: RouteStats) -> Double {
        minutes(distanceKm: stats.distance, ascentM: stats.ascent)
    }

    /// «6ч 20м» или «45м».
    static func format(minutes: Double) -> String {
        let m = Int(minutes.rounded())
        guard m >= 60 else { return "\(m)м" }
        return "\(m / 60)ч \(String(format: "%02d", m % 60))м"
    }

    static func short(distanceKm: Double, ascentM: Double) -> String {
        format(minutes: minutes(distanceKm: distanceKm, ascentM: ascentM))
    }
}
